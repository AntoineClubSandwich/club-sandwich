/// Spacing scale for the Club Sandwich design system.
///
/// Every gap, padding and margin in `Ds*` components must come from this
/// scale — never a raw literal — so rhythm stays consistent across the
/// whole design system.
abstract final class DsSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
  static const double xxxl = 48;
  static const double huge = 64;
}
